from __future__ import annotations

import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    UUID,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base


class Voucher(Base):
    """SQLAlchemy ORM model for the ``vouchers`` table.

    Columns follow the design schema exactly.  All timestamps are stored as
    TIMESTAMPTZ (timezone-aware) and all comparisons use UTC.
    """

    __tablename__ = "vouchers"

    __table_args__ = (
        # Enforce allowed values at the database level
        CheckConstraint(
            "status IN ('unused', 'consumed', 'revoked')",
            name="ck_vouchers_status",
        ),
        CheckConstraint(
            "activation_mode IN ('use-activated', 'pre-activated')",
            name="ck_vouchers_activation_mode",
        ),
        CheckConstraint(
            "duration_minutes >= 1 AND duration_minutes <= 525600",
            name="ck_vouchers_duration_minutes",
        ),
        # Indexes for common query patterns (Req 1.6, 3.5)
        Index("idx_vouchers_code", "code"),
        Index("idx_vouchers_status", "status"),
        Index("idx_vouchers_created_at", text("created_at DESC")),
        Index("idx_vouchers_expires_at", "expires_at"),
    )

    # Primary key — UUID generated by the database
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )

    # The 12-character voucher code — unique, required
    code: Mapped[str] = mapped_column(
        String(12),
        nullable=False,
        unique=True,
    )

    # Lifecycle status — starts as 'unused'
    status: Mapped[str] = mapped_column(
        String(12),
        nullable=False,
        default="unused",
        server_default=text("'unused'"),
    )

    # Controls when the expiry clock starts
    activation_mode: Mapped[str] = mapped_column(
        String(15),
        nullable=False,
        default="use-activated",
        server_default=text("'use-activated'"),
    )

    # Expiry duration in whole minutes (1 minute – 365 days)
    duration_minutes: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # Creation timestamp (set by the database)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=text("NOW()"),
        default=lambda: datetime.now(timezone.utc),
    )

    # Expiry timestamp — NULL for use-activated until first successful auth
    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        default=None,
    )

    # Set at first (and only) successful authentication
    consumed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        default=None,
    )

    # Set when an admin manually revokes the voucher
    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        default=None,
    )

    # The admin who created this voucher — SET NULL on admin deletion
    created_by: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("admins.id", ondelete="SET NULL"),
        nullable=True,
        default=None,
    )

    # ------------------------------------------------------------------
    # Helper methods
    # ------------------------------------------------------------------

    def is_expired(self) -> bool:
        """Return ``True`` if this voucher's expiry time has passed.

        Returns ``False`` when ``expires_at`` is ``None`` — a use-activated
        voucher that has never been used has no expiry clock yet and must not
        be treated as expired (Req 3.3).

        All comparisons use UTC (Req 3.5). The stored value may be either
        timezone-aware (asyncpg returns aware datetimes for ``TIMESTAMPTZ``
        columns) or naive; naive values are interpreted as UTC so the
        comparison is always valid.
        """
        if self.expires_at is None:
            return False
        now = datetime.now(timezone.utc)
        expires_at = self.expires_at
        if expires_at.tzinfo is None:
            expires_at = expires_at.replace(tzinfo=timezone.utc)
        return now > expires_at

    def __repr__(self) -> str:  # pragma: no cover
        return (
            f"<Voucher code={self.code!r} status={self.status!r} "
            f"activation_mode={self.activation_mode!r}>"
        )
